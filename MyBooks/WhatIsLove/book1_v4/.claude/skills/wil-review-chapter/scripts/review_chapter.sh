#!/usr/bin/env bash
# Build a review document for a chapter of "What Is Love? God's Perfect Love".
#
#   review_chapter.sh <chapter-number> <book-root> [-o out.html] [extra build_review.py flags]
#
# This is a defaults wrapper. All the real work is rich-html-doc/scripts/build_review.py;
# nothing here duplicates it. Anything after the known flags is passed straight through,
# so an unusual chapter can override any default.

set -euo pipefail

if [ $# -lt 2 ]; then
  sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'
  exit 2
fi

NUM="$1"; shift
ROOT="$1"; shift
NN=$(printf '%02d' "$NUM")

OUT=""
KEY_VER="v1"
PASSTHRU=()
while [ $# -gt 0 ]; do
  case "$1" in
    -o|--out) OUT="$2"; shift 2 ;;
    --key-version) KEY_VER="$2"; shift 2 ;;   # bump after the chapter text changes
    *) PASSTHRU+=("$1"); shift ;;
  esac
done

SRC="$ROOT/chapters/chapter_${NN}.md"
[ -f "$SRC" ] || { echo "no such chapter: $SRC" >&2; exit 1; }
SRC=$(cd "$(dirname "$SRC")" && pwd)/$(basename "$SRC")   # absolute: the export prints it

# --- locate the two skills we depend on ---------------------------------------
find_asset() {  # find_asset <skill-name> <relative-path>
  local n="$1" rel="$2" d
  for d in "$(dirname "$0")/../.." \
           "$HOME/.claude/skills" "$HOME/.config/claude/skills" \
           "/mnt/skills/user" "/mnt/skills/public" "$PWD"; do
    if [ -f "$d/$n/$rel" ]; then
      echo "$(cd "$d/$n" && pwd)/$rel"
      return 0
    fi
  done
  return 1
}

BUILD=$(find_asset rich-html-doc scripts/build_review.py) || {
  echo "Could not find rich-html-doc/scripts/build_review.py." >&2
  echo "This skill is a wrapper — install or locate rich-html-doc first." >&2
  exit 1; }

BRAND=$(find_asset brand-love assets/love-brand.css) || BRAND=""

# --- chapter title, verbatim from the '# ' heading ----------------------------
TITLE=$(sed -n 's/^# \{1,\}//p' "$SRC" | head -1)

WORDS=(Zero One Two Three Four Five Six Seven Eight Nine Ten Eleven Twelve
       Thirteen Fourteen Fifteen Sixteen Seventeen Eighteen Nineteen Twenty
       "Twenty-One" "Twenty-Two" "Twenty-Three" "Twenty-Four" "Twenty-Five")
WORD="${WORDS[$((10#$NN))]:-$NUM}"

OUT="${OUT:-ch${NUM}-review.html}"

FONTS="https://fonts.googleapis.com/css2?family=Cinzel:wght@400;500;600;700&family=Cinzel+Decorative:wght@400;700&family=Libre+Baskerville:ital,wght@0,400;0,700;1,400&family=Inter:wght@400;500;600&display=swap"

ARGS=( "$SRC" -o "$OUT"
       --source "$SRC"
       --title "$TITLE"
       --eyebrow "Chapter $WORD"
       --subtitle "Chapter $NUM · Review"
       --label "Chapter $NUM"
       --key "wil-ch${NUM}-suggestions-${KEY_VER}"
       --root-class "love love--red love--dark"
       --generator "wil-review-chapter skill (wraps rich-html-doc/scripts/build_review.py)"
       --fonts "$FONTS" )
[ -n "$BRAND" ] && ARGS+=( --brand-css "$BRAND" )
[ ${#PASSTHRU[@]} -gt 0 ] && ARGS+=( "${PASSTHRU[@]}" )

python3 "$BUILD" "${ARGS[@]}"

# --- stamp provenance into the output file --------------------------------
# Respect a passed-through --source override (used when the real file lives
# on the user's device and $SRC above is only a staged copy).
FINAL_SRC="$SRC"
for ((i=0; i<${#PASSTHRU[@]}; i++)); do
  if [ "${PASSTHRU[$i]}" = "--source" ]; then
    FINAL_SRC="${PASSTHRU[$((i+1))]}"
  fi
done

# Stamp provenance as an HTML comment. This is deliberately NOT shown on the
# page: which skill built the file is of no interest while reading it, and the
# absolute source path is noise on screen. It is here for a future session that
# is handed this file and needs to know what made it and how to rebuild it —
# the reader-facing counterpart is the generation date, which build_review.py
# puts in the colophon, and the "Generated by" line it writes into the export.
python3 - "$OUT" "$FINAL_SRC" <<'PY'
import sys
path, src = sys.argv[1], sys.argv[2]
with open(path) as f:
    content = f.read()
comment = (
    "<!-- generated-by: wil-review-chapter skill "
    "(wraps rich-html-doc/scripts/build_review.py) -->\n"
    f"<!-- source-of-truth: {src} -->\n"
    "<!-- regenerate: wil-review-chapter/scripts/review_chapter.sh -->\n"
)
content = content.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n" + comment, 1)
with open(path, "w") as f:
    f.write(content)
PY

echo "source of truth: $FINAL_SRC" >&2
echo "review doc (disposable): $OUT" >&2
